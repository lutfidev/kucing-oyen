"""Embed the finite Oyen rig subset; run after generate.py. No raster assets."""
from pathlib import Path
import sys
import json

ROOT = Path(__file__).resolve().parents[2]
sources = sorted((ROOT / 'assets/art/v2/cats').glob('oyen-*.svg'))
out = ['// Generated by tool/art_v2/embed_puzzle.py; do not edit.', '// dart format off',
       'const puzzleCatSources = <String, String>{']
for source in sources:
    svg = source.read_text(encoding='utf-8')
    inner = svg[svg.index('>') + 1:svg.rindex('</svg>')]
    out.append(f"  'cats/{source.stem}': r'''{inner}''',")
out.append('};\n')
manifest = json.loads((ROOT / 'assets/art/v2/manifest.json').read_text(encoding='utf-8'))
accessories = {key: meta for key, meta in manifest['assets'].items()
               if key.startswith('accessories/')}
out.append('const navigationAccessorySources = <String, String>{')
for key, meta in accessories.items():
    svg = (ROOT / 'assets/art/v2' / meta['file']).read_text(encoding='utf-8')
    inner = svg[svg.index('>') + 1:svg.rindex('</svg>')]
    out.append(f"  '{key}': r'''{inner}''',")
out.append('};\n')
out.append('const navigationAccessoryMetadata = <String, dynamic>' +
           json.dumps(accessories, ensure_ascii=False, separators=(',', ':')) + ';\n')
target = ROOT / 'lib/game/render/v2/puzzle_cat_sources.dart'
content = '\n'.join(out)
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != content:
        raise SystemExit('Puzzle Oyen subset is stale; run embed_puzzle.py')
else:
    target.write_text(content, encoding='utf-8')
